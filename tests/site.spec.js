import {test,expect} from '@playwright/test';
test('imported catalogue supports categories, search, paging, and empty results',async({page})=>{
 await page.goto('/');
 await expect(page.locator('#result-count')).toContainText('478 catalogue entries');
 await expect(page.locator('.product')).toHaveCount(24);
 await page.getByRole('button',{name:'Show more products'}).click();
 await expect(page.locator('.product')).toHaveCount(48);
 await page.getByLabel('Browse by category').selectOption('Safety Wear');
 await expect(page.locator('.product-category')).toHaveText(Array(22).fill('Safety Wear'));
 await page.getByRole('searchbox').fill('nonexistent');
 await expect(page.getByText('No products found.')).toBeVisible();
 await page.getByRole('button',{name:'Clear filters'}).click();
 await expect(page.locator('.product')).toHaveCount(24);
 await page.getByRole('searchbox').fill('Basin Mixers');
 await expect(page.locator('.product')).toHaveCount(1);
 await expect(page.locator('.product-category')).toHaveText('Plumbing');
});
test('real product enquiry preserves selection and prepares an email',async({page})=>{
 await page.goto('/');
 await page.getByRole('searchbox').fill('Basin Mixers');
 await page.getByRole('button',{name:'Basin Mixers',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.getByRole('button',{name:'Add to enquiry',exact:true}).click();
 await page.reload();await expect(page.locator('.count')).toHaveText('1');
 await page.getByRole('button',{name:/Your enquiry/}).click();
 await expect(page.locator('.enquiry-item')).toContainText('Basin Mixers');
 await page.getByLabel('Project details & quantities').fill('Please quote for 2 mixers.');
 await page.locator('#email-enquiry').evaluate(el=>{el.addEventListener('click',e=>e.preventDefault());el.click();});
 const href=await page.locator('#email-enquiry').getAttribute('href');
 expect(href).toContain('nairobicentralhardwareltd@gmail.com');
 expect(decodeURIComponent(href)).toContain('Please quote for 2 mixers.');
 expect(decodeURIComponent(href)).toContain('Basin Mixers');
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'Download list'}).click();
 expect((await download).suggestedFilename()).toBe('nch-product-enquiry.txt');
 await page.getByRole('button',{name:'Remove Basin Mixers',exact:true}).click();
 await expect(page.locator('.empty-list')).toBeVisible();
 await page.getByRole('button',{name:'Close enquiry'}).click();
 await expect(page.locator('.count')).toHaveText('0');
});
